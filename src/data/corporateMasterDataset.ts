/**
 * 기업 규모별 필터 함수
 */
export function getCorporateItemsByScale(scale?: CorporateScale | 'all'): VerifiedServiceItem[] {
  if (!scale || scale === 'all') {
    return [...CORPORATE_MASTER_DATASET].sort((a, b) => a.serviceName.localeCompare(b.serviceName, 'ko-KR'));
  }
  return CORPORATE_MASTER_DATASET.filter((item) => item.scale === scale).sort((a, b) =>
    a.serviceName.localeCompare(b.serviceName, 'ko-KR')
  );
}
